export const translations: Record<AppLocale, TranslationMessages> = { ru, en, zh };

export type TranslationKey = string;

export function translate(
  locale: AppLocale,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const parts = key.split('.');
  let node: unknown = translations[locale];
  for (const part of parts) {
    if (node && typeof node === 'object' && part in (node as object)) {
      node = (node as Record<string, unknown>)[part];
    } else {
      node = translations.ru;
      for (const p of parts) {
        if (node && typeof node === 'object' && p in (node as object)) {
          node = (node as Record<string, unknown>)[p];
        } else {
          return key;
        }
      }
      break;
    }
  }
  if (typeof node !== 'string') return key;
  if (!params) return node;
  return node.replace(/\{\{(\w+)\}\}/g, (_, name: string) =>
    params[name] != null ? String(params[name]) : '',
  );
}
